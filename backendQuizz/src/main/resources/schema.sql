CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    category VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE quiz ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL REFERENCES quiz(id) ON DELETE CASCADE,
    statement VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS answer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES question(id) ON DELETE CASCADE,
    option_key VARCHAR(100) NOT NULL,
    answer_text VARCHAR(300) NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_answer_question_key UNIQUE (question_id, option_key)
);

CREATE TABLE IF NOT EXISTS quiz_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    quiz_id BIGINT NOT NULL REFERENCES quiz(id),
    score INTEGER NOT NULL CHECK (score >= 0),
    total_questions INTEGER NOT NULL CHECK (total_questions > 0),
    max_streak INTEGER NOT NULL CHECK (max_streak >= 0),
    average_response_seconds DOUBLE PRECISION NOT NULL CHECK (average_response_seconds >= 0),
    completed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_result_score CHECK (score <= total_questions),
    CONSTRAINT ck_result_streak CHECK (max_streak <= total_questions)
);

CREATE INDEX IF NOT EXISTS idx_quiz_result_user_completed
    ON quiz_result (user_id, completed_at DESC);

CREATE TABLE IF NOT EXISTS auth_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_friend (
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    friend_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, friend_id),
    CONSTRAINT ck_user_friend_not_self CHECK (user_id <> friend_id)
);

CREATE INDEX IF NOT EXISTS idx_user_friend_friend_id ON user_friend (friend_id);

CREATE TABLE IF NOT EXISTS contact_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    message VARCHAR(2000) NOT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS revision_sheet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(100) NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(500) NOT NULL,
    category VARCHAR(100) NOT NULL,
    reading_minutes INTEGER NOT NULL CHECK (reading_minutes > 0),
    color VARCHAR(30) NOT NULL,
    quiz_slug VARCHAR(100) REFERENCES quiz(slug),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE revision_sheet ADD COLUMN IF NOT EXISTS quiz_slug VARCHAR(100) REFERENCES quiz(slug);
ALTER TABLE revision_sheet ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS revision_notion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sheet_id BIGINT NOT NULL REFERENCES revision_sheet(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    content VARCHAR(1000) NOT NULL,
    CONSTRAINT uq_revision_notion_position UNIQUE (sheet_id, position)
);
