CREATE TABLE quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) not null,
    description VARCHAR(500),
    category VARCHAR(100),
    difficulty VARCHAR(100),
    type VARCHAR(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP

);

CREATE TABLE question(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement VARCHAR(500) NOT NULL,
    img_path VARCHAR(255),
    quiz_id BIGINT NOT NULL,

    CONSTRAINT fk_question_quiz
        FOREIGN KEY (quiz_id)
        REFERENCES quiz(id)
        ON DELETE CASCADE

);

CREATE TABLE answer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_text VARCHAR(300) NOT NULL,
    is_correct BOOlEAN NOT NULL DEFAULT FALSE,
    question_id BIGINT NOT NULL,

    CONSTRAINT fk_answer_question
        FOREIGN KEY (question_id)
        REFERENCES question(id)
        ON DELETE CASCADE

);

CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(100) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 elo_pt INT NOT NULL DEFAULT 1000,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score INT NOT NULL,
    total_questions INT NOT NULL,

    elo_before INT NOT NULL,
    elo_change INT NOT NULL,
    elo_after INT NOT NULL,

    completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    user_id BIGINT NOT NULL,
    quiz_id BIGINT NOT NULL,

    CONSTRAINT fk_result_user
    FOREIGN KEY (user_id)
    REFERENCES users(id)
    ON DELETE CASCADE,

    CONSTRAINT fk_result_quiz
    FOREIGN KEY (quiz_id)
    REFERENCES quiz(id)
    ON DELETE CASCADE
);

CREATE TABLE challenge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    challenger_id BIGINT NOT NULL,
    opponent_id BIGINT NOT NULL,
    quiz_id BIGINT NOT NULL,

    challenger_score INT,
    opponent_score INT,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_challenge_challenger
        FOREIGN KEY (challenger_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_challenge_opponent
        FOREIGN KEY (opponent_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_challenge_quiz
        FOREIGN KEY (quiz_id)
        REFERENCES quiz(id)
        ON DELETE CASCADE
);

CREATE TABLE friends (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    friend_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_friends_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_friends_friend
        FOREIGN KEY (friend_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT unique_friendship
        UNIQUE (user_id, friend_id)
);
